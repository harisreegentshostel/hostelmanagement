-- 5. RPC FUNCTION: STRICT RESIDENT EMAIL VERIFICATION
-- ------------------------------------------------------------------------------
-- Security Definer function to check if an email belongs to an admitted resident
CREATE OR REPLACE FUNCTION public.check_resident_email(lookup_email TEXT)
RETURNS BOOLEAN
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  RETURN EXISTS (
    SELECT 1 FROM public.residents
    WHERE LOWER(TRIM(email)) = LOWER(TRIM(lookup_email))
  );
END;
$$;

GRANT EXECUTE ON FUNCTION public.check_resident_email(TEXT) TO anon, authenticated, service_role;


-- ------------------------------------------------------------------------------
-- 6. RPC FUNCTION: AUTOMATED MONTHLY FEE ACCUMULATION ENGINE
-- ------------------------------------------------------------------------------
-- Formula: Total Due = Existing Pending Balance + Current Month's Fixed Monthly Fee
-- Advances next_fee_payment_date to next month, preserving the resident's fixed due day
-- Logs each billing cycle into public.fee_transactions for full financial audit trail
CREATE OR REPLACE FUNCTION public.process_all_monthly_fees()
RETURNS INTEGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  r RECORD;
  v_updated_count INTEGER := 0;
  v_current_pending NUMERIC(10, 2);
  v_next_due DATE;
  v_billing_date DATE;
  v_fixed_day INTEGER;
  v_monthly_fee NUMERIC(10, 2);
  v_already_billed BOOLEAN;
  v_month_name TEXT;
BEGIN
  FOR r IN
    SELECT id, name, monthly_fee, pending, next_fee_payment_date, fee_due_day, last_fee_applied_date
    FROM public.residents
    WHERE next_fee_payment_date IS NOT NULL
      AND next_fee_payment_date <= CURRENT_DATE
      AND monthly_fee > 0
  LOOP
    v_current_pending := COALESCE(r.pending, 0);
    v_next_due := r.next_fee_payment_date;
    v_monthly_fee := r.monthly_fee;
    v_fixed_day := COALESCE(r.fee_due_day, EXTRACT(DAY FROM r.next_fee_payment_date)::INTEGER, 5);

    WHILE v_next_due <= CURRENT_DATE LOOP
      v_billing_date := v_next_due;

      -- Idempotent check: has this resident already been billed for this cycle?
      SELECT EXISTS (
        SELECT 1 FROM public.fee_transactions
        WHERE resident_id = r.id
          AND type = 'MONTHLY_FEE'
          AND billing_date = v_billing_date
      ) INTO v_already_billed;

      IF NOT v_already_billed THEN
        v_month_name := TO_CHAR(v_billing_date, 'FMMonth YYYY');

        -- Log transaction in fee ledger
        INSERT INTO public.fee_transactions (
          resident_id,
          type,
          amount,
          balance_before,
          balance_after,
          billing_date,
          description
        ) VALUES (
          r.id,
          'MONTHLY_FEE',
          v_monthly_fee,
          v_current_pending,
          v_current_pending + v_monthly_fee,
          v_billing_date,
          'Monthly hostel fee added for ' || TRIM(v_month_name)
        );

        -- Accumulate formula: Total Due = Existing Pending + Current Month Fee
        v_current_pending := v_current_pending + v_monthly_fee;
      END IF;

      -- Advance next due date by 1 month, preserving fixed due day
      v_next_due := (v_next_due + INTERVAL '1 month')::DATE;
      BEGIN
        v_next_due := MAKE_DATE(
          EXTRACT(YEAR FROM v_next_due)::INTEGER,
          EXTRACT(MONTH FROM v_next_due)::INTEGER,
          LEAST(v_fixed_day, EXTRACT(DAY FROM (DATE_TRUNC('month', v_next_due) + INTERVAL '1 month - 1 day'))::INTEGER)
        );
      EXCEPTION WHEN OTHERS THEN
        v_next_due := v_next_due;
      END;
    END LOOP;

    -- Update resident record with new accumulated pending balance and next payment date
    UPDATE public.residents
    SET
      pending = v_current_pending,
      next_fee_payment_date = v_next_due,
      fee_due_day = v_fixed_day,
      last_fee_applied_date = v_billing_date,
      updated_at = NOW()
    WHERE id = r.id;

    v_updated_count := v_updated_count + 1;
  END LOOP;

  RETURN v_updated_count;
END;
$$;

GRANT EXECUTE ON FUNCTION public.process_all_monthly_fees() TO anon, authenticated, service_role;


