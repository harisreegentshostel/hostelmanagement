-- Helper function in public schema to detect role strictly from app_metadata (tamper-proof)
CREATE OR REPLACE FUNCTION public.get_user_role()
RETURNS TEXT
LANGUAGE sql
STABLE
SECURITY DEFINER
AS $$
  SELECT CASE 
    -- 1. App metadata (secure, set only by server/admin) or designated admin email
    WHEN LOWER(COALESCE(auth.jwt() -> 'app_metadata' ->> 'role', '')) = 'admin'
         OR LOWER(auth.jwt() ->> 'email') IN ('admin@harisreehostel.com', 'harisreehostel@admin.com') THEN 'admin'
    -- 2. Kitchen staff app metadata or designated kitchen email
    WHEN LOWER(COALESCE(auth.jwt() -> 'app_metadata' ->> 'role', '')) IN ('kitchen_staff', 'kitchen', 'staff')
         OR LOWER(auth.jwt() ->> 'email') IN ('kitchen@harisreehostel.com', 'harisreehostel@staff.com') THEN 'kitchen_staff'
    -- 3. All other accounts are strictly resident level
    ELSE 'resident'
  END;
$$;

GRANT EXECUTE ON FUNCTION public.get_user_role() TO anon, authenticated, service_role;

